export function buildShadowrocketNodeSubscriptionUrl(requestUrl) {
    const nodeUrl = new URL(requestUrl);
    NODE_TARGET_PARAMS.forEach(param => nodeUrl.searchParams.delete(param));
    nodeUrl.searchParams.set('target', 'base64');
    nodeUrl.searchParams.set('builtin', 'true');
    return nodeUrl.toString();
}

